import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { shellQuote } from "./cli-helpers.mjs";

const OMP_RESULT_SENTINEL = "__unclecode_omp_worker_result__";
export const OMP_CONTROL_URL_ENV = "UNCLECODE_AGENT_CONSOLE_QA_OMP_URL";

export function writeOmpExecutorFixture(tmp) {
  const root = path.join(tmp, "agent-console-omp");
  const packageRoot = path.join(root, "pi-coding-agent");
  mkdirSync(path.join(packageRoot, "bin"), { recursive: true });
  writeFileSync(
    path.join(packageRoot, "package.json"),
    `${JSON.stringify({ name: "@oh-my-pi/pi-coding-agent", version: "0.0.0-agent-console-qa" })}\n`,
  );

  // Never executed: the lookup only needs a resolvable executable to anchor on.
  const binPath = path.join(packageRoot, "bin", "omp");
  writeFileSync(binPath, "#!/bin/sh\nexit 1\n");
  chmodSync(binPath, 0o755);

  const workerPath = path.join(root, "omp-worker-shim.mjs");
  writeFileSync(workerPath, ompWorkerShimSource());
  const bunPath = path.join(root, "bun");
  writeFileSync(
    bunPath,
    `#!/bin/sh\nexec ${shellQuote(process.execPath)} ${shellQuote(workerPath)} "$@"\n`,
  );
  chmodSync(bunPath, 0o755);
  return { binPath, bunPath };
}

// Deterministic offline stand-in for the Bun OMP work executor. It speaks the
// published stdin/stdout contract and parks each lane at the control server.
function ompWorkerShimSource() {
  return `// Generated by scripts/runtime-qa/agent-console-smoke-fixture.mjs.
const SENTINEL = ${JSON.stringify(OMP_RESULT_SENTINEL)};
const entry = process.argv[2] ?? "";
if (!/omp-worker-entry\\.[cm]?[jt]s$/.test(entry)) {
  // Only the work-executor boundary is emulated; the OMP auth catalog worker
  // keeps its ordinary unavailable path.
  process.stderr.write("agent console QA bun shim: unsupported entrypoint\\n");
  process.exit(1);
}
const controlUrl = process.env[${JSON.stringify(OMP_CONTROL_URL_ENV)}];
if (!controlUrl) {
  process.stderr.write("agent console QA bun shim: missing control url\\n");
  process.exit(1);
}
let raw = "";
process.stdin.setEncoding("utf8");
for await (const chunk of process.stdin) {
  raw += chunk;
}
const response = await fetch(controlUrl, {
  method: "POST",
  headers: { "content-type": "application/json" },
  body: raw,
});
const payload = await response.json();
const result = {
  ok: true,
  result: { text: payload.text, provider: "agent-console-qa", model: JSON.parse(raw).model },
};
process.stdout.write(SENTINEL + " " + JSON.stringify(result) + "\\n");
`;
}
